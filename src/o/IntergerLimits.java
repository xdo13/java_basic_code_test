package o;

public class IntergerLimits {
    public static void main(String[] args) {
        System.out.println("정수형의 표현 범위");
        System.out.println("byte 형:" +Byte.MIN_VALUE  +" ~ "+ Byte.MAX_VALUE);
        System.out.println("short 형:" +Short.MIN_VALUE  +" ~ "+ Byte.MAX_VALUE);
        System.out.println("int  형:" +Integer.MIN_VALUE  +" ~ "+ Byte.MAX_VALUE);
        System.out.println("long 형:" +Long.MIN_VALUE  +" ~ "+ Byte.MAX_VALUE);
    }
}
